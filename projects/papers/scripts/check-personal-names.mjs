import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import {nameLabel,personalReference,nameRegistry} from '../src/personal-names.mjs';
import {people,works} from '../src/catalog.mjs';
const person=id=>people.find(p=>p.id===id),work=id=>works.find(w=>w.id===id);
assert.equal(nameLabel(person('gauss')),'Carl Friedrich <span class="person-surname">Gauss</span>');
assert.equal(nameLabel(person('johann-bernoulli')),'Johann <span class="person-surname">Bernoulli</span>');
assert.equal(nameLabel(person('mangoldt')),'Hans von <span class="person-surname">Mangoldt</span>');
assert.equal(nameLabel(person('gauss'),'Gaussian geometry'),'Gaussian geometry');
assert.equal(nameLabel(person('euler'),String.raw`\(\operatorname{Euler}(x)\)`),String.raw`\(\operatorname{Euler}(x)\)`);
const general=personalReference(person('gauss'),'Gauss’s','../');
assert(general.includes('href="../people/gauss/"'));
assert(general.includes('>Gauss</span>’s'));
const specific=personalReference(person('gauss'),'Gauss','../',work('gauss-1828'));
assert(specific.includes('href="../gauss-1828/"'));
assert(specific.includes('data-reference-work="gauss-1828"'));
assert.throws(()=>personalReference(person('riemann'),'Riemann','../',work('gauss-1828')),/not an author/);
const ambiguous=nameRegistry([{id:'j',name:'Johann Bernoulli'},{id:'b',name:'Jacob Bernoulli'}],'../');
assert(ambiguous.every(p=>!p.aliases.includes('Bernoulli')),'A shared surname must not silently identify one person');
new vm.Script(fs.readFileSync(new URL('../public/name-links.js',import.meta.url),'utf8'));
const html=id=>fs.readFileSync(new URL('../dist/'+id+'/index.html',import.meta.url),'utf8');
assert(html('riemann-1859').includes('data-person="jacobi" data-reference-work="jacobi-1829"'));
assert(html('riemann-1854').includes('data-person="gauss" data-reference-work="gauss-1828"'));
for(const id of ['leibniz','johann-bernoulli'])assert(html('euler-1751').includes(`data-person="${id}" data-reference-work="leibniz-bernoulli-1745"`));
assert(html('people/gauss').includes('../../riemann-1854/#metric-plan'),'Specific references remain in person backlinks');
const catalogue=html('');
assert(catalogue.includes('data-person="poincare" data-reference-work="poincare-1892" href="poincare-1892/"'));
assert(catalogue.includes('<span class="person-surname">Stillwell</span>'));
const bib=fs.readFileSync(new URL('../dist/riemann-1859/citation.bib',import.meta.url),'utf8');
assert(bib.includes('Bernhard Riemann'));assert(!bib.includes('<span'));
console.log('Validated surname-only typography, specific-work versus author-work links, author identity checks, backlinks, ambiguity handling, unchanged math labels, and plain-text bibliographic exports.');
