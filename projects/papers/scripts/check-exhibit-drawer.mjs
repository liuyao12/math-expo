import assert from 'node:assert/strict';
import fs from 'node:fs';
import {drawerState} from '../public/exhibit-drawer.mjs';
import {exhibitSceneForPassage} from '../public/zeta-math.mjs';
let state={context:null,manual:false,dismissed:false,suspended:false,open:false};
const send=event=>state=drawerState(Object.freeze(state),event);
assert.equal(send({type:'context',id:null}).open,false);
assert.equal(send({type:'context',id:'euler-product'}).open,true);
assert.equal(send({type:'close'}).open,false);
assert.equal(send({type:'context',id:'euler-product'}).open,false,'Scrolling within the dismissed passage must not reopen it.');
assert.equal(send({type:'context',id:null}).open,false);
assert.equal(send({type:'context',id:'euler-product'}).open,true,'Returning to a relevant passage should reopen it.');
assert.equal(send({type:'suspend',value:true}).open,false);
assert.equal(send({type:'suspend',value:false}).open,true);
assert.equal(send({type:'close'}).open,false);
assert.equal(send({type:'reveal'}).open,true);
assert.equal(send({type:'context',id:null}).open,true,'A manually opened exhibit stays available for exploration.');
assert.equal(send({type:'toggle'}).open,false);
assert.equal(send({type:'context',id:'density'}).open,true);
for(const id of ['euler-product','continued-zeta','functional-equation','zero-count','hypothesis','prime-count','formula','mobius','density','smooth-part','numerical-evidence'])assert(exhibitSceneForPassage(id),id);
for(const id of [undefined,'opening','gamma-integral','theta','ordering','zero-product'])assert.equal(exhibitSceneForPassage(id),null,id);
assert.equal(exhibitSceneForPassage('density').id,'prime-inversion');
assert.equal(exhibitSceneForPassage('numerical-evidence').id,'prime-digits');
for(const file of ['exhibit-drawer.mjs','reading-apparatus.mjs'])assert.equal(fs.readFileSync(new URL('../public/'+file,import.meta.url),'utf8'),fs.readFileSync(new URL('../dist/'+file,import.meta.url),'utf8'));
console.log('Validated relevant-passage drawer entry, dismissal, reverse reentry, manual exploration, authored-commentary suspension and both formula aliases.');
