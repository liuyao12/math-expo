export function fundamentalLabels(type,m){
 const s=m.reduce((a,b)=>a+b,0),d=(a,b)=>m[a-1]-m[b-1];
 if(type==='E6')return[d(5,6),(2*(m[3]+m[4]+m[5])-m[0]-m[1]-m[2])/3,d(1,2),d(4,5),d(2,3),d(3,4)];
 if(type==='E7')return[d(6,7),d(1,2),m[4]+m[5]+m[6]-s/3,d(2,3),d(5,6),d(3,4),d(4,5)];
 if(type==='E8')return[d(8,9),d(2,3),d(7,8),-m[1]-m[2]-m[3],d(6,7),d(3,4),d(5,6),d(4,5)];
 if(type==='F4')return[m[0]-m[1]-m[2]-m[3],d(2,3),2*m[3],d(3,4)];
 if(type==='G2')return[-3*m[1],d(2,3)];
 throw Error('Unknown weight model');
}
