"""Render a narrated, noninteractive exterior-area loop.

All mathematical labels come from the reader's KaTeX atlas, generated by
render_tangent_area_math.mjs. Pillow draws only geometry and prose.
"""
import argparse
import json
import math
import tempfile
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont, ImageChops

OUT = Path(__file__).resolve().parents[1] / "assets"
W = H = 720
AA = 2
FPS = 14
DURATION = 26
BG = "#0b0e16"
WHITE = "#edf1f7"
MUTED = "#a4b1c1"
YELLOW, CYAN = "#ffd166", "#58c4dd"
RED, BLUE = "#f07178", "#58a6ff"
P = [1 / math.sqrt(3)] * 3
Q = [1 / math.sqrt(2), -1 / math.sqrt(2), 0]
R = [1 / math.sqrt(6), 1 / math.sqrt(6), -2 / math.sqrt(6)]


def dot(a, b):
    return sum(x * y for x, y in zip(a, b))


def add(a, b):
    return [x + y for x, y in zip(a, b)]


def scale(a, k):
    return [x * k for x in a]


def vector(a):
    return add(scale(Q, a[0]), scale(R, a[1]))


def mix(a, b, t):
    return [x + t * (y - x) for x, y in zip(a, b)]


def smooth(t):
    t = min(1, max(0, t))
    return t * t * (3 - 2 * t)


def patch(w, epsilon):
    if epsilon == 0:
        return w
    norm = math.sqrt(1 + epsilon * epsilon * dot(w, w))
    return add(scale(w, 1 / norm), scale(P, -epsilon * dot(w, w) / (norm * (norm + 1))))


def coordinate_vectors(t):
    a = math.atan2(.1, .9) + .8 * t
    b = math.atan2(.9, .12) + .8 * t + .2 * math.sin(t)
    return [math.hypot(.9, .1) * math.cos(a), math.hypot(.9, .1) * math.sin(a)], [math.hypot(.12, .9) * math.cos(b), math.hypot(.12, .9) * math.sin(b)]


def scene(t):
    initial_u, initial_v = [.9, .1], [.12, .9]
    if t < 4.5:
        z = smooth(t / 4.5)
        return dict(phase="zoom", u=initial_u, v=initial_v, axis=0, projection=0,
                    zoom=z, title="Zoom in on a surface.", caption="Curvature fades. A linear measuring space remains.")
    if t < 13.5:
        local = t - 4.5
        u, v = coordinate_vectors(local)
        axis = min(2, int(local / 3))
        return dict(phase="coordinate", u=u, v=v, axis=axis, projection=0, zoom=1,
                    title="One arrow, one signed reading.",
                    caption="One fixed coordinate function. Two changing inputs.")
    local = t - 13.5
    if local < 1.5:
        previous_u, previous_v = coordinate_vectors(9)
        a = smooth(local / 1.5)
        u, v = mix(previous_u, initial_u, a), mix(previous_v, initial_v, a)
        caption = "Project to the coordinate plane."
        phase = "projection"
    elif local < 3:
        u, v = initial_u, initial_v
        caption = "The order sets the orientation."
        phase = "positive"
    elif local < 6:
        a = smooth((local - 3) / 3)
        u, v = mix(initial_u, initial_v, a), mix(initial_v, initial_u, a)
        caption = "Exchange the two inputs."
        phase = "swap"
    elif local < 7.5:
        u, v = initial_v, initial_u
        caption = "Same magnitude. Opposite sign."
        phase = "negative"
    elif local < 9.5:
        u = initial_v
        v = mix(initial_u, scale(u, .8), smooth((local - 7.5) / 2))
        caption = "Parallel inputs give zero."
        phase = "align"
    else:
        u, v = initial_v, scale(initial_v, .8)
        caption = "Parallel inputs give zero."
        phase = "parallel"
    return dict(phase=phase, u=u, v=v, axis=0, projection=smooth(local / 1.5),
                zoom=1, title="Two arrows, one signed area.", caption=caption)


class Film:
    def __init__(self):
        self.atlas = Image.open(OUT / "tangent-area-math.png").convert("RGBA")
        metadata = json.loads((OUT / "tangent-area-math.json").read_text())
        factor = metadata["scale"]
        self.labels = {
            key: self.atlas.crop((round(box["x"] * factor), round(box["y"] * factor),
                                  round((box["x"] + box["w"]) * factor),
                                  round((box["y"] + box["h"]) * factor)))
            for key, box in metadata["labels"].items()
        }
        font = "/System/Library/Fonts/Supplemental/Arial.ttf"
        self.title_font = ImageFont.truetype(font, 32 * AA)
        self.caption_font = ImageFont.truetype(font, 23 * AA)
        self.small_font = ImageFont.truetype(font, 20 * AA)
        self.clip = Image.new("L", (W * AA, H * AA))
        ImageDraw.Draw(self.clip).rectangle((20 * AA, 180 * AA, 525 * AA, 610 * AA), fill=255)

    def render(self, t):
        data = scene(t)
        u, v = vector(data["u"]), vector(data["v"])
        coordinate = data["phase"] in ("zoom", "coordinate")
        reading_fade = 1
        if data["phase"] == "coordinate":
            local = (t - 4.5) % 3
            reading_fade = min(smooth(local / .22), smooth((3 - local) / .22))
        values = [u[data["axis"]], v[data["axis"]]] if coordinate else [u[0] * v[1] - u[1] * v[0]]
        image = Image.new("RGBA", (W * AA, H * AA), BG)
        draw = ImageDraw.Draw(image)

        def text(x, y, value, font, fill=WHITE, anchor="mm"):
            draw.text((x * AA, y * AA), value, font=font, fill=fill, anchor=anchor)

        def math_label(x, y, key, opacity=1):
            label = self.labels[key]
            if opacity < 1:
                label = label.copy()
                label.putalpha(label.getchannel("A").point(lambda x: round(x * opacity)))
            image.alpha_composite(label, (round(x * AA - label.width / 2), round(y * AA - label.height / 2)))

        text(360, 42, data["title"], self.title_font)
        if data["phase"] == "zoom":
            math_label(360, 119, "tangent")
        elif coordinate:
            math_label(360, 119, "form_" + "xyz"[data["axis"]], reading_fade)
        else:
            math_label(360, 119, "omega")

        layer = Image.new("RGBA", image.size)
        geom = ImageDraw.Draw(layer)
        tilt = mix([.75, .5, .35], [.86, .36, .24], data["zoom"])
        normal = add(scale(P, tilt[0]), add(scale(Q, tilt[1]), scale(R, tilt[2])))
        normal = scale(normal, 1 / math.sqrt(dot(normal, normal)))
        yaw, pitch = math.atan2(normal[1], normal[0]), math.asin(normal[2])
        horizontal = [-math.sin(yaw), math.cos(yaw), 0]
        vertical = [-math.sin(pitch) * math.cos(yaw), -math.sin(pitch) * math.sin(yaw), math.cos(pitch)]

        def project(w):
            plane = [dot(w, horizontal), dot(w, vertical)]
            target = [w[0], w[1]]
            a = data["projection"]
            return (270 + 135 * ((1 - a) * plane[0] + a * target[0]),
                    390 - 135 * ((1 - a) * plane[1] + a * target[1]))

        def pixels(points):
            return [(round(x * AA), round(y * AA)) for x, y in points]

        def line(points, fill, width=1):
            geom.line(pixels(points), fill=fill, width=max(1, round(width * AA)), joint="curve")

        def world_line(points, fill, width=1):
            line([project(w) for w in points], fill, width)

        epsilon = .85 * (1 - data["zoom"]) ** 2
        if epsilon > .16:
            center = project(scale(P, -1 / epsilon))
            radius = 135 / epsilon
            opacity = round(55 * min(1, (epsilon - .16) / .3))
            geom.ellipse(pixels([(center[0] - radius, center[1] - radius),
                                 (center[0] + radius, center[1] + radius)]),
                         outline=(72, 104, 115, opacity + 30), width=AA)
        grid_alpha = round(150 * (1 - data["projection"]))
        for i in range(-5, 6):
            a = i * .22
            for swap in (False, True):
                curve = [patch(vector([b, a] if swap else [a, b]), epsilon) for b in [j * .055 for j in range(-20, 21)]]
                world_line(curve, (72, 111, 119, grid_alpha), .85)
        if data["projection"] > 0:
            alpha = round(135 * data["projection"])
            for i in range(-6, 7):
                a = i * .2
                line([(270 + 135 * a, 228), (270 + 135 * a, 552)], (62, 83, 106, alpha), .8)
                line([(108, 390 - 135 * a), (432, 390 - 135 * a)], (62, 83, 106, alpha), .8)
            line([(95, 390), (455, 390)], (160, 177, 196, alpha), 1.2)
            line([(270, 563), (270, 216)], (160, 177, 196, alpha), 1.2)
        if data["phase"] == "coordinate":
            a, b = Q[data["axis"]], R[data["axis"]]
            for value in [-.6, -.3, 0, .3, .6]:
                candidates = []
                if abs(b) > 1e-10:
                    candidates += [[x, (value - a * x) / b] for x in [-1.1, 1.1]]
                if abs(a) > 1e-10:
                    candidates += [[(value - b * y) / a, y] for y in [-1.1, 1.1]]
                candidates = [w for w in candidates if max(map(abs, w)) <= 1.10001]
                if len(candidates) >= 2:
                    world_line([vector(w) for w in candidates[:2]], (139, 169, 185, round(165 * reading_fade)), 1.2)

        show_vectors = smooth((data["zoom"] - .65) / .35)
        if show_vectors:
            polygon = [project(w) for w in [[0, 0, 0], u, add(u, v), v]]
            color = RED if values[0] >= 0 else BLUE
            rgb = tuple(int(color[i:i + 2], 16) for i in (1, 3, 5))
            if not coordinate and abs(values[0]) < 1e-10:
                rgb = (130, 150, 170)
            fill = (*rgb, round(45 * show_vectors)) if not coordinate else (148, 176, 191, 18)
            geom.polygon(pixels(polygon), fill=fill)
            line(polygon + [polygon[0]], (*rgb, round(150 * show_vectors)) if not coordinate else (115, 143, 159, 130), 1)
            for name, w, color in [("u", u, YELLOW), ("v", v, CYAN)]:
                start, end = project([0, 0, 0]), project(w)
                dx, dy = end[0] - start[0], end[1] - start[1]
                length = math.hypot(dx, dy)
                rgb = tuple(int(color[i:i + 2], 16) for i in (1, 3, 5))
                rgba = (*rgb, round(255 * show_vectors))
                line([start, end], rgba, 3)
                if length > 1:
                    a, b = dx / length, dy / length
                    geom.polygon(pixels([end, (end[0] - 11 * a + 4 * b, end[1] - 11 * b - 4 * a),
                                         (end[0] - 11 * a - 4 * b, end[1] - 11 * b + 4 * a)]), fill=rgba)
        origin = project([0, 0, 0])
        geom.ellipse(pixels([(origin[0] - 3, origin[1] - 3), (origin[0] + 3, origin[1] + 3)]), fill=WHITE)
        layer.putalpha(ImageChops.multiply(layer.getchannel("A"), self.clip))
        image.alpha_composite(layer)

        if show_vectors:
            for name, w, side in [("u", u, -1), ("v", v, 1)]:
                x, y = project(w)
                dx, dy = x - origin[0], y - origin[1]
                length = max(1, math.hypot(dx, dy))
                math_label(x + side * (-dy / length) * 18, y + side * dx / length * 18, name, show_vectors)
        math_label(origin[0] - 15, origin[1] + 17, "origin", .65)
        if data["projection"] > .95:
            math_label(458, 405, "x")
            math_label(252, 213, "y")
            math_label(405, 410, "tick_plus", .7)
            math_label(135, 410, "tick_minus", .7)
            math_label(251, 255, "tick_plus", .7)
            math_label(251, 525, "tick_minus", .7)

        meter_opacity = show_vectors * reading_fade
        if data["phase"] == "projection":
            meter_opacity = smooth((t - 14.1) / .6)
        positions = [567, 668] if coordinate else [620]
        for i, (x, value) in enumerate(zip(positions, values)):
            if meter_opacity <= 0:
                continue
            top, bottom, zero = 270, 510, 390
            opacity = round(255 * meter_opacity)
            draw.rounded_rectangle((int((x - 9) * AA), top * AA, int((x + 9) * AA), bottom * AA),
                                   radius=5 * AA, fill=(17, 29, 43, opacity), outline=(114, 137, 159, opacity), width=AA)
            end = zero - 120 * value
            fill = RED if value >= 0 else BLUE
            rgb = tuple(int(fill[j:j + 2], 16) for j in (1, 3, 5))
            draw.rectangle(((x - 6) * AA, min(zero, end) * AA, (x + 6) * AA, max(zero, end) * AA),
                           fill=(*rgb, opacity))
            draw.line(((x - 17) * AA, zero * AA, (x + 17) * AA, zero * AA), fill=(197, 211, 225, opacity), width=AA)
            for y, key in [(top, "tick_plus"), (zero, "tick_zero"), (bottom, "tick_minus")]:
                math_label(x - 31, y, key, .7 * meter_opacity)
            key = ("u_" if i == 0 else "v_") + "xyz"[data["axis"]] if coordinate else "pair"
            math_label(x, 229, key, meter_opacity)
            number = max(-100, min(100, round(value * 100)))
            math_label(x, 553, "number_" + str(number), meter_opacity)

        footer = "eps" if data["phase"] == "zoom" else "oneform" if coordinate else "swap" if data["phase"] in ("swap", "negative") else "parallel" if data["phase"] in ("align", "parallel") else "determinant"
        math_label(360, 624, footer)
        text(360, 681, data["caption"], self.caption_font, MUTED)
        opacity = min(smooth(t / .65), 1 - smooth((t - 25.1) / .7))
        if opacity < 1:
            image = Image.blend(Image.new("RGBA", image.size, BG), image, opacity)
        result = image.convert("RGB").resize((W, H), Image.Resampling.LANCZOS)
        return result, dict(t=round(t, 6), phase=data["phase"], u=u, v=v,
                            reading=data["axis"] if coordinate else 3, values=values)


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--preview-dir", type=Path)
    args = parser.parse_args()
    film = Film()
    manifest = []
    durations = []
    key_times = [2, 4.5, 6.5, 10.5, 15.8, 18, 20.3, 24]
    with tempfile.TemporaryDirectory(prefix="tangent-area-film-") as temporary:
        folder = Path(temporary)
        files = []
        for i in range(round(DURATION * FPS)):
            frame, sample = film.render(i / FPS)
            file = folder / f"{i:04}.png"
            frame.save(file)
            files.append(file)
            manifest.append(sample)
            durations.append(70 if i % 7 else 80)
        samples = [film.render(t)[0] for t in key_times]
        montage = Image.new("RGB", (W * len(samples), H), BG)
        for i, frame in enumerate(samples):
            montage.paste(frame, (i * W, 0))
        palette = montage.resize((W * 2, H // 2)).quantize(colors=256, method=Image.Quantize.MEDIANCUT)
        indexed = [Image.open(file).quantize(palette=palette, dither=Image.Dither.NONE) for file in files]
        indexed[0].save(OUT / "tangent-area.gif", save_all=True, append_images=indexed[1:],
                        duration=durations, loop=0, disposal=1, optimize=True)
        film.render(15.8)[0].save(OUT / "tangent-area-still.png")
        (OUT / "tangent-area-film.json").write_text(json.dumps({
            "width": W, "height": H, "duration_ms": sum(durations), "frames": manifest
        }, separators=(",", ":")) + "\n")
        if args.preview_dir:
            args.preview_dir.mkdir(parents=True, exist_ok=True)
            for t, frame in zip(key_times, samples):
                frame.save(args.preview_dir / f"frame-{t}.png")
    with Image.open(OUT / "tangent-area.gif") as movie:
        assert movie.info.get("loop") == 0
        assert movie.size == (W, H)
    print(f"Rendered {len(files)} frames; {(OUT / 'tangent-area.gif').stat().st_size / 1e6:.2f} MB.")
